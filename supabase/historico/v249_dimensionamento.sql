--   3. `importar_backup` NÃO é portada. Era o caminho da origem para mover dados entre
--      instalações; aqui o backup é o do painel (dump diário + weekly cifrado). Uma RPC que
--      substitui TODOS os dados numa transação é superfície grande demais para o ganho.
--
-- As tabelas nascem SEM privilégio e ganham o grant explicitamente — não dependemos de
-- qual `ALTER DEFAULT PRIVILEGES` está valendo nesta base.

-- NO JCN: guarda de dono adaptada (as funcoes SECURITY DEFINER aqui pertencem
-- a 'postgres'; no self-host, a 'chabra_admin') e sem o insert em
-- public.schema_migrations, que e o rastreador do painel self-host.
-- dim_portes e dim_parametros nascem VAZIAS: os dados do painel vieram do
-- scripts/dim01-carga.sh, que carrega o cadastro da consultoria da Chabra e
-- nao atravessa para ca. Ver a nota da v253 sobre o modulo ficar dormente.

