-- v249 — Dimensionamento (DIM-01): o schema do Chabra Dimensiona dentro do painel_sst.
--
-- Numerada v249 em 2026-09-22 depois de a v243 ser tomada por outra frente enquanto
-- esta era escrita (v243–v248 entraram no mesmo dia). O número sai do banco, no ato.
--
-- ADITIVA. Nada é removido aqui: as 7 tabelas `prod_*` do módulo Produtividade e as
-- permissões atuais continuam intactas até a v244, que só entra depois que a migração
-- de dados e o front estiverem provados. Rollback: scripts/sql/v249_rollback_dimensionamento.sql.
--
-- Origem: joaojefferson-hash/Dimensionamento_Chabra @ e5671c2, schema real extraído por
-- `pg_dump --schema-only` do Supabase do João em 2026-09-22 (12 tabelas, 11 funções, zero
-- tipos custom). As tabelas entram com prefixo `dim_` porque `unidades`, `colaboradores` e
-- `funcoes` JÁ EXISTEM no painel_sst com outro significado.
--
-- Três decisões que se afastam da origem, de propósito:
--   1. Identidade: a origem usa `papel_atual()`/`pode_editar()` lendo `app_metadata.papel`
--      (Supabase). Aqui quem decide é `public.caller_eh_admin()` (v242, memoizado por
--      transação) — o módulo é admin-only por decisão do operador (D7).
--   2. `GENERATED BY DEFAULT AS IDENTITY` no lugar de `ALWAYS`: a carga de dados da Fase 1.2
