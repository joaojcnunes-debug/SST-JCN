-- ─── 7) RPCs de escrita ──────────────────────────────────────────────────────
-- Portadas da origem com três mudanças:
--   • A guarda era `auth.uid() is null` + `pode_editar()` (papel do app_metadata). Aqui é
--     `coalesce(public.caller_eh_admin(), false)` — e SEM `coalesce` uma guarda contra NULL
--     não dispara, lição que já custou um furo nesta base (SEC-GESTAO-05).
--   • São SECURITY INVOKER, não DEFINER: a RLS acima já barra o não-Admin, então não há
--     motivo para criar superfície que contorna política. A guarda fica como segunda
--     tranca, para o caso de alguém afrouxar a policy no futuro.
--   • `aplicar_sincronizacao_sst` na origem LIBERAVA quando `auth.uid()` era nulo (o caminho
--     do agendamento). Aqui exige Admin sempre: a rota `/api/dimensionamento/sincronizar`
--     chama com a sessão do próprio usuário, nunca com service_role.

create or replace function public.dim_definir_alocacoes(p_colaborador uuid, p_alocacoes jsonb)
returns void
language plpgsql
set search_path = public
as $_$
begin
  if not coalesce(public.caller_eh_admin(), false) then
    raise exception 'Só administradores alteram o dimensionamento.' using errcode = '42501';
  end if;
  if not exists (select 1 from public.dim_colaboradores where id = p_colaborador) then
    raise exception 'Colaborador não encontrado' using errcode = 'P0002';
  end if;

  delete from public.dim_colaborador_unidades where colaborador_id = p_colaborador;

  insert into public.dim_colaborador_unidades (colaborador_id, unidade_id, percentual)
  select p_colaborador,
         (e.elem->>'unidadeId')::uuid,
         least(100, round((e.elem->>'percentual')::numeric, 2))
  from jsonb_array_elements(coalesce(p_alocacoes, '[]'::jsonb)) as e(elem)
  where (e.elem->>'unidadeId') ~ '^[0-9a-f-]{36}$'
    and coalesce((e.elem->>'percentual')::numeric, 0) > 0
    and exists (select 1 from public.dim_unidades u where u.id = (e.elem->>'unidadeId')::uuid);
end;
$_$;

create or replace function public.dim_substituir_demanda_ano(p_ano integer, p_linhas jsonb, p_condicao text default null)
returns jsonb
language plpgsql
set search_path = public
as $_$
declare
  apagadas integer;
  inseridas integer;
  cond text;
begin
  if not coalesce(public.caller_eh_admin(), false) then
    raise exception 'Só administradores alteram o dimensionamento.' using errcode = '42501';
  end if;
  if p_ano is null or p_ano < 2000 or p_ano > 2100 or p_linhas is null or jsonb_typeof(p_linhas) <> 'array' then
    raise exception 'Dados inválidos' using errcode = '22023';
  end if;
  cond := nullif(trim(coalesce(p_condicao, '')), '');
  if cond is not null and cond not in ('mensal', 'exclusiva_tst', 'sem_avaliacao', 'contrato_novo') then
    raise exception 'Condição inválida' using errcode = '22023';
  end if;

  with ids as (
    select distinct (e->>'unidade_id')::uuid as unidade_id
      from jsonb_array_elements(p_linhas) e
     where (e->>'unidade_id') ~ '^[0-9a-f-]{36}$')
  delete from public.dim_demanda_mensal d using ids
   where d.unidade_id = ids.unidade_id and d.ano = p_ano
     and (cond is null or d.condicao = cond);
  get diagnostics apagadas = row_count;

  insert into public.dim_demanda_mensal (unidade_id, ano, mes, condicao, porte, quantidade)
  select (e->>'unidade_id')::uuid, p_ano, (e->>'mes')::int,
         coalesce(cond, case when e->>'condicao' in ('exclusiva_tst', 'sem_avaliacao', 'contrato_novo')
                             then e->>'condicao' else 'mensal' end),
         case when exists (select 1 from public.dim_portes p where p.codigo = e->>'porte') then e->>'porte' else 'P' end,
         greatest(0, round(coalesce(nullif(e->>'quantidade', '')::numeric, 0)))::int
  from jsonb_array_elements(p_linhas) e
  where (e->>'unidade_id') ~ '^[0-9a-f-]{36}$'
    and (e->>'mes') ~ '^\d{1,2}$' and (e->>'mes')::int between 1 and 12
    and greatest(0, round(coalesce(nullif(e->>'quantidade', '')::numeric, 0)))::int > 0
    and exists (select 1 from public.dim_unidades u where u.id = (e->>'unidade_id')::uuid)
  on conflict (unidade_id, ano, mes, condicao, porte) do update set quantidade = excluded.quantidade;
  get diagnostics inseridas = row_count;

  return jsonb_build_object('apagadas', apagadas, 'inseridas', inseridas, 'condicao', cond);
end;
$_$;

create or replace function public.dim_aplicar_sincronizacao_sst(p_payload jsonb)
returns jsonb
language plpgsql
set search_path = public
as $_$
declare
  ano int := coalesce(nullif(p_payload->>'ano', '')::int, extract(year from now())::int);
  u jsonb;
  uid uuid;
  aplicar boolean;
  apagadas int := 0;
  inseridas int := 0;
  meses int := 0;
  total_demanda int;
  total_atendidas int;
begin
  if not coalesce(public.caller_eh_admin(), false) then
    raise exception 'Só administradores aplicam a sincronização.' using errcode = '42501';
  end if;
  if p_payload is null or jsonb_typeof(p_payload->'unidades') <> 'array' then
    raise exception 'Lote inválido' using errcode = '22023';
  end if;
  if ano < 2000 or ano > 2100 then
    raise exception 'Ano inválido' using errcode = '22023';
  end if;

  for u in select * from jsonb_array_elements(p_payload->'unidades') loop
    uid := nullif(u->>'unidade_id', '')::uuid;
    aplicar := coalesce((u->>'aplicar')::boolean, false);
    total_demanda := 0; total_atendidas := 0;

    if aplicar and uid is not null then
      delete from public.dim_demanda_mensal d where d.unidade_id = uid and d.ano = ano;
      get diagnostics apagadas = row_count;

      insert into public.dim_demanda_mensal (unidade_id, ano, mes, condicao, porte, quantidade)
      select uid, ano, (d->>'mes')::int,
             case when d->>'condicao' in ('exclusiva_tst', 'sem_avaliacao', 'contrato_novo')
                  then d->>'condicao' else 'mensal' end,
             case when exists (select 1 from public.dim_portes pt where pt.codigo = d->>'porte')
                  then d->>'porte' else 'P' end,
             greatest(0, round(coalesce(nullif(d->>'quantidade', '')::numeric, 0)))::int
      from jsonb_array_elements(case when jsonb_typeof(u->'demanda') = 'array' then u->'demanda' else '[]'::jsonb end) as d
      where (d->>'mes') ~ '^\d{1,2}$' and (d->>'mes')::int between 1 and 12
        and greatest(0, round(coalesce(nullif(d->>'quantidade', '')::numeric, 0)))::int > 0
      on conflict (unidade_id, ano, mes, condicao, porte) do update set quantidade = excluded.quantidade;
      get diagnostics inseridas = row_count;
      total_demanda := inseridas;

      for meses in select generate_series(1, 12) loop
        if (u->'atendidas') ? meses::text then
          insert into public.dim_unidade_mes (unidade_id, ano, mes, clientes_ativos, atendidas, atendidas_porte)
          select uid, ano, meses,
                 coalesce((select clientes_ativos from public.dim_unidade_mes m
                            where m.unidade_id = uid and m.ano = ano and m.mes = meses), 0),
                 (select coalesce(sum(value::int), 0) from jsonb_each_text(u->'atendidas'->meses::text)),
                 u->'atendidas'->meses::text
          on conflict (unidade_id, ano, mes) do update
            set atendidas = excluded.atendidas, atendidas_porte = excluded.atendidas_porte;
          total_atendidas := total_atendidas + 1;
        end if;
      end loop;
    end if;

    insert into public.dim_sincronizacao_sst
      (ano, unidade_id, codigo_api, cobertura, ultima_varredura_em, documentos,
       demanda_gravada, atendidas_gravadas, aplicada, mensagem)
    values (ano, uid, u->>'codigo_api', u->>'cobertura',
            nullif(u->>'ultima_varredura_em', '')::timestamptz,
            greatest(0, coalesce(nullif(u->>'documentos', '')::int, 0)),
            total_demanda, total_atendidas, aplicar, u->>'mensagem');
  end loop;

  return jsonb_build_object('ano', ano, 'unidades', jsonb_array_length(p_payload->'unidades'));
end;
$_$;

