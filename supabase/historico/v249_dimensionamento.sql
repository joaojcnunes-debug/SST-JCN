create or replace function public.dim_checar_soma_alocacoes() returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare total numeric;
begin
  select coalesce(sum(percentual), 0) into total
    from public.dim_colaborador_unidades where colaborador_id = new.colaborador_id;
  if total > 100.0001 then
    raise exception 'A soma das alocações do colaborador não pode passar de 100%% (atual: %)', total || '%'
      using errcode = '23514';
  end if;
  return new;
end $$;

-- Histórico: grava QUEM mudou o quê. Só o gatilho escreve (a tabela é ingravável pelo app).
-- `app.dim_historico = 'off'` desliga durante a carga de dados da Fase 1.2, para não gerar
-- um evento por linha importada.
create or replace function public.dim_registrar_historico() returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  antes   jsonb;
  depois  jsonb;
  rid     text;
  v_email text;
  v_nome  text;
begin
  if coalesce(current_setting('app.dim_historico', true), '') = 'off' then
    return coalesce(new, old);
  end if;

  if tg_op in ('UPDATE','DELETE') then antes  := to_jsonb(old); end if;
  if tg_op in ('INSERT','UPDATE') then depois := to_jsonb(new); end if;
  if tg_op = 'UPDATE' and (antes - 'updated_at') = (depois - 'updated_at') then
    return new;
  end if;

  if tg_table_name in ('dim_colaborador_unidades','dim_demanda_mensal','dim_unidade_mes') then
    if antes is not null then
      antes := antes || jsonb_build_object('unidade_nome',
        (select x.nome from public.dim_unidades x where x.id = (antes->>'unidade_id')::uuid));
    end if;
    if depois is not null then
      depois := depois || jsonb_build_object('unidade_nome',
        (select x.nome from public.dim_unidades x where x.id = (depois->>'unidade_id')::uuid));
    end if;
  end if;
  if tg_table_name = 'dim_colaborador_unidades' then
    if antes is not null then
      antes := antes || jsonb_build_object('colaborador_nome',
        (select x.nome from public.dim_colaboradores x where x.id = (antes->>'colaborador_id')::uuid));
    end if;
    if depois is not null then
      depois := depois || jsonb_build_object('colaborador_nome',
        (select x.nome from public.dim_colaboradores x where x.id = (depois->>'colaborador_id')::uuid));
    end if;
  end if;

  v_email := lower(nullif(auth.jwt() ->> 'email', ''));
  select u.nome into v_nome from public.usuarios u where lower(u.email) = v_email limit 1;

  rid := coalesce(depois->>'id', antes->>'id', depois->>'codigo', antes->>'codigo',
                  concat_ws('/', coalesce(depois, antes)->>'unidade_id',
                                 coalesce(depois, antes)->>'colaborador_id',
                                 coalesce(depois, antes)->>'ano',
                                 coalesce(depois, antes)->>'mes',
                                 coalesce(depois, antes)->>'condicao',
                                 coalesce(depois, antes)->>'porte'));

  insert into public.dim_historico (usuario_email, usuario_nome, tabela, operacao, registro_id, antes, depois)
  values (v_email, v_nome, tg_table_name, lower(tg_op), rid, antes, depois);

  return coalesce(new, old);
end $$;

-- ─── 4) Gatilhos ─────────────────────────────────────────────────────────────

do $$
declare
  t text;
  com_updated text[] := array['dim_unidades','dim_funcoes','dim_colaboradores','dim_documentos','dim_parametros'];
  com_historico text[] := array['dim_unidades','dim_funcoes','dim_colaboradores','dim_colaborador_unidades',
                                'dim_portes','dim_clientes_porte','dim_documentos','dim_demanda_mensal','dim_unidade_mes'];
begin
  foreach t in array com_updated loop
    execute format('drop trigger if exists %I on public.%I', t || '_set_updated_at', t);
    execute format('create trigger %I before update on public.%I for each row execute function public.dim_set_updated_at()',
                   t || '_set_updated_at', t);
  end loop;

  foreach t in array com_historico loop
    execute format('drop trigger if exists %I on public.%I', t || '_historico', t);
    execute format('create trigger %I after insert or update or delete on public.%I for each row execute function public.dim_registrar_historico()',
                   t || '_historico', t);
  end loop;

  -- parâmetros: linha única, só UPDATE interessa
  drop trigger if exists dim_parametros_historico on public.dim_parametros;
  create trigger dim_parametros_historico after update on public.dim_parametros
    for each row execute function public.dim_registrar_historico();

  drop trigger if exists dim_colaborador_unidades_soma on public.dim_colaborador_unidades;
  create trigger dim_colaborador_unidades_soma after insert or update on public.dim_colaborador_unidades
    for each row execute function public.dim_checar_soma_alocacoes();
end $$;

-- ─── 5) Privilégio e RLS — admin-only, fechado por padrão ────────────────────
-- Não dependemos do ALTER DEFAULT PRIVILEGES desta base: revogamos tudo e concedemos
-- explicitamente. `anon` nunca recebe nada. A RLS (caller_eh_admin) é quem barra de fato —
-- a trava por módulo (rls_modulo_tabelas) está em modo `log` e NÃO barra ninguém hoje.

do $$
declare
  t text;
  tabelas text[] := array['dim_unidades','dim_funcoes','dim_colaboradores','dim_colaborador_unidades',
                          'dim_portes','dim_clientes_porte','dim_documentos','dim_parametros',
                          'dim_demanda_mensal','dim_unidade_mes','dim_sincronizacao_sst','dim_historico'];
begin
  foreach t in array tabelas loop
    execute format('revoke all on public.%I from public, anon, authenticated', t);
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists dim_admin on public.%I', t);
  end loop;

  -- 11 tabelas: Admin faz tudo
  foreach t in array tabelas loop
    continue when t = 'dim_historico';
    execute format('grant select, insert, update, delete on public.%I to authenticated', t);
    execute format('create policy dim_admin on public.%I for all to authenticated '
                   'using (coalesce(public.caller_eh_admin(), false)) '
                   'with check (coalesce(public.caller_eh_admin(), false))', t);
  end loop;

  -- histórico: leitura para Admin; escrita SÓ pelo gatilho (security definer)
  grant select on public.dim_historico to authenticated;
  create policy dim_admin on public.dim_historico for select to authenticated
    using (coalesce(public.caller_eh_admin(), false));
end $$;

